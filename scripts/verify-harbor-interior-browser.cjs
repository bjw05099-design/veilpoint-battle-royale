'use strict';
// Real browser rendering of the production CH01 simulation and both renderer
// paths. Fixture coordinates are disclosed; this is not native GPU performance.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
async function verifyHarborInterior({rpc}){
 const root=path.resolve(__dirname,'..');
 const files=['simulation','public-city-footpaths','visibility','performance','graphics',
  'aden-hall-lights','story-public-court','renderer','story-consequences',
  'ch01-civic-recovery','ch01-street-flood','aden-public-hall','story-slice',
  'story-harbor-ambience','story-footfall'];
 const scripts=files.map(name=>'<script>'+fs.readFileSync(path.join(root,'src',name+'.js'),'utf8')
   .replace(/<\/script/gi,'<\\/script')+'</script>').join('');
 await rpc('Page.navigate',{url:'about:blank'});
 const tree=await rpc('Page.getFrameTree');
 await rpc('Emulation.setDeviceMetricsOverride',{width:1366,height:768,deviceScaleFactor:1,mobile:false});
 await rpc('Page.setDocumentContent',{frameId:tree.frameTree.frame.id,
  html:'<!doctype html><meta charset="utf-8"><style>body{margin:0;background:#142328;color:#ddd;font:14px sans-serif}canvas{display:block;width:100vw;height:calc(100vh - 32px)}p{margin:0;height:32px;padding:0 12px;line-height:32px}</style><p>CH01 loading hall · production simulation / renderer verification fixture</p><canvas id="view"></canvas>'+scripts});
 const evaluate=async expression=>{
  const r=await rpc('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});
  if(r.exceptionDetails)throw Error('CH01 hall rendering: '+JSON.stringify(r.exceptionDetails));
  return r.result?.value;
 };
 const evidence=await evaluate(`(()=>{
  const S=VeilpointStorySlice,Sim=VeilpointSim,s=S.createState();
  Object.assign(s.world.player,{x:0,z:-18});S.interact(s);
  for(const b of s.world.bots){b.health=0;b.alive=false;b.shots=12;}
  s.phase='records';s.combat.cleared=true;
  Object.assign(s.world.player,{x:42,z:-26,yaw:0,pitch:.26});
  Object.assign(s.kimJiyoon,{x:42,z:-24});
  for(let i=0;i<120;i++)S.step(s,1/60,{forward:true});
  const saved=S.serialize(s),restored=S.restore(saved);
  const renderer=new VeilpointRenderer(document.getElementById('view'));
  renderer.draw(restored.world);window.hallQA={state:restored,renderer};
  return {z:restored.world.player.z,inside:!!Sim.harborPassageAt(restored.world.player,restored.world.obstacles),
   material:VeilpointStoryFootfall.surfaceAt(restored),saveRoundTrip:S.serialize(restored)===saved,
   backend:renderer.gl?'webgl2':'canvas2d',glError:renderer.gl?renderer.gl.getError():null};
 })()`);
 assert.ok(evidence.z<-37&&evidence.z>-40);assert.equal(evidence.inside,true);
 assert.equal(evidence.material,'interior');assert.equal(evidence.saveRoundTrip,true);
 if(evidence.backend==='webgl2')assert.equal(evidence.glError,0);
 await evaluate('new Promise(resolve=>requestAnimationFrame(()=>{hallQA.renderer.draw(hallQA.state.world);requestAnimationFrame(()=>resolve(true));}))');
 const primary=await rpc('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 // Use a fresh real Canvas2D context, explicitly selecting the supported
 // fallback, rather than a fake canvas or a screenshot generated by a test.
 await evaluate(`(()=>{
  const old=document.getElementById('view'),canvas=document.createElement('canvas');
  canvas.id='view';old.replaceWith(canvas);
  const adapter={get clientWidth(){return canvas.clientWidth},get clientHeight(){return canvas.clientHeight},
   get width(){return canvas.width},set width(v){canvas.width=v},
   get height(){return canvas.height},set height(v){canvas.height=v},
   getContext:type=>type==='webgl2'?null:canvas.getContext(type)};
  hallQA.renderer=new VeilpointRenderer(adapter);hallQA.renderer.draw(hallQA.state.world);
  return true;
 })()`);
 const fallback=await rpc('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 const crossed=await evaluate(`(()=>{
  const s=hallQA.state;
  for(let i=0;i<130;i++)VeilpointStorySlice.step(s,1/60,{forward:true});
  return {z:s.world.player.z,phase:s.phase,blocked:VeilpointSim.blocked(s.world.player.x,s.world.player.z,.85,s.world.obstacles)};
 })()`);
 assert.ok(crossed.z<-49);assert.equal(crossed.phase,'records');assert.equal(crossed.blocked,false);
 return {...evidence,exitZ:crossed.z,primaryScreenshot:primary.data,fallbackScreenshot:fallback.data};
}
module.exports={verifyHarborInterior};
