"""Validate authored fictional mission stops against actual Aden public roads."""

import argparse
import math
from pathlib import Path

# Local projected centimetres. Changed only when the registered source
# revision or the fictional mission's authored walking legs change.
ORIGIN = (412321, 85622)
BRIEF = (414546, 88127)
FIRST_TURN = (416771, 90631)
JUNCTION = (421279, 87128)
WITNESS = (425708, 83517)
NOTICE = (414451, 79690)
MERGE = (419145, 76078)
DESK = (415785, 72207)
PATHS = {
    "Brief": [ORIGIN, BRIEF],
    "Decision": [BRIEF, FIRST_TURN, JUNCTION],
    "Witness": [JUNCTION, WITNESS],
    "Notice": [JUNCTION, NOTICE],
    "FromWitness": [WITNESS, MERGE],
    "FromNotice": [NOTICE, MERGE],
    "Handoff": [MERGE, DESK],
    "ReceiptArchive": [MERGE, (409640, 65128)],
}


def edge_distance(p, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    scale = dx * dx + dy * dy
    t = min(1, max(0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / scale)) if scale else 0
    return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)


def samples(a, b):
    count = math.ceil(math.dist(a, b) / 35)
    for i in range(count + 1):
        yield tuple(x + (y - x) * i / count for x, y in zip(a, b))


def blocked(p, ring):
    inside = False
    for a, b in zip(ring, ring[1:] + ring[:1]):
        if edge_distance(p, a, b) < 78:
            return True
        if (a[1] > p[1]) != (b[1] > p[1]) and p[0] < a[0] + (b[0] - a[0]) * (p[1] - a[1]) / (b[1] - a[1]):
            inside = not inside
    return inside


def generate(data):
    roads = [(a, b) for road in data["roadsCm"] for a, b in zip(road, road[1:])]
    lots = [(min(x for x, _ in ring), max(x for x, _ in ring),
             min(y for _, y in ring), max(y for _, y in ring), ring)
            for ring in data["footprintsCm"]]
    result = ['// Authored and checked against registered public road geometry.',
              '// Generated by scripts/build-native-aden-dispatch.py.', '#pragma once',
              'namespace VPAdenDispatchData {', 'struct FPoint { int X; int Y; };',
              f'inline constexpr char Revision[] = "{data["revision"]}";']
    for name, leg in PATHS.items():
        for a, b in zip(leg, leg[1:]):
            nearby = [r for x0, x1, y0, y1, r in lots if x0 <= max(a[0], b[0]) + 78
                      and x1 >= min(a[0], b[0]) - 78 and y0 <= max(a[1], b[1]) + 78 and y1 >= min(a[1], b[1]) - 78]
            # At least one original source segment supports this entire leg.
            if not any(edge_distance(a, u, v) < 4 and edge_distance(b, u, v) < 4 for u, v in roads):
                raise ValueError(f"{name}: authored leg off registered road")
            if any(blocked(point, lot) for point in samples(a, b) for lot in nearby):
                raise ValueError(f"{name}: projected footprint clearance")
        points = ', '.join('{' + str(x) + ', ' + str(y) + '}' for x, y in leg)
        result.append(f'inline constexpr FPoint {name}[] = {{{points}}};')
    return '\n'.join([*result, '}', ''])


if __name__ == "__main__":
    from aden_source_geometry import build

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('header', type=Path)
    args = parser.parse_args()
    args.header.write_text(generate(build(args.source)), encoding='ascii', newline='\n')
