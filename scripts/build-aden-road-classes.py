"""Bake the ordered highway classes from the registered Aden civilian archive."""

import argparse
import gzip
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = "cda6123261bb4ab9049f8aef4086c7e60994a5bc5052748ffa945f294e8de1df"
CLASSES = {
    "primary": "Primary",
    "primary_link": "PrimaryLink",
    "tertiary": "Tertiary",
    "tertiary_link": "TertiaryLink",
    "residential": "Residential",
    "living_street": "LivingStreet",
    "unclassified": "Unclassified",
}


def build(source):
    raw = gzip.decompress(source.read_bytes())
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Aden civilian source differs from the registered archive")
    data = json.loads(raw)
    roads = [
        CLASSES[feature["properties"]["class"]]
        for feature in data["features"]
        if feature["geometry"]["type"] == "LineString" and feature["properties"]["layer"] == "street"
    ]
    if len(roads) != 183:
        raise ValueError("Aden road class count differs from the registered geometry")
    rows = [
        "    " + ", ".join("EHighway::" + kind for kind in roads[i:i + 4]) + ","
        for i in range(0, len(roads), 4)
    ]
    return "\n".join([
        "// Generated by scripts/build-aden-road-classes.py from the pinned ODbL archive.",
        "#pragma once", '#include "VPAdenRoadStyle.h"', "", "namespace VPAdenRoads", "{",
        f'inline constexpr char SourceSha256[] = "{SOURCE_SHA256}";',
        "inline constexpr EHighway SourceClasses[] = {", *rows, "};", "}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    args.header.write_text(build(args.archive), encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
