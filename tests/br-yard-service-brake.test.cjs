'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const Sim=require('../src/simulation.js');
function driving(seed=20261107){
 const g=Sim.newMatch(seed,1);g.status='playing';
 const v=g.vehicle,p=g.player;
 p.x=v.x-Math.cos(v.yaw)*2.65;p.z=v.z-Math.sin(v.yaw)*2.65;
 assert.deepEqual(Sim.operateYardShuttle(g),{ok:true,event:'enter'});
 return g;
}
test('driver can use remappable physical crouch control as gradual 60Hz service brake',()=>{
 const g=driving();
 for(let i=0;i<75;i++)Sim.tick(g,1/60,{forward:true});
 const v=g.vehicle,body=g.obstacles.find(o=>o.routeId==='br-yard-shuttle');
 assert.ok(v.speed>2);
 const first=v.speed,oldFuel=v.fuel,oldX=v.x;
 Sim.tick(g,1/60,{forward:true,crouch:true});
 assert.ok(v.speed<first&&v.speed>0,'first frame decelerates rather than teleporting to zero');
 assert.equal(Sim.shuttleStatus(g).braking,true);
 assert.ok(v.fuel<=oldFuel);
 for(let i=0;i<55;i++)Sim.tick(g,1/60,{forward:true,crouch:true});
 assert.equal(v.speed,0);
 assert.equal(v.x,body.x);
 assert.equal(v.z,body.z);
 assert.ok(v.x>=oldX,'braking cannot rewind world position');
 const stopX=v.x,stopFuel=v.fuel;
 for(let i=0;i<35;i++)Sim.tick(g,1/60,{forward:true,crouch:true});
 assert.equal(v.x,stopX,'holding brake overrides throttle and does not create motion');
 assert.equal(v.fuel,stopFuel,'stationary truck consumes no distance-based fuel');
 assert.equal(Sim.shuttleStatus(g).braking,true);
 Sim.tick(g,1/60,{forward:true});
 assert.ok(v.speed>0,'releasing brake restores finite normal acceleration');
 assert.equal(Sim.shuttleStatus(g).braking,false);
});
test('service brake is vehicle-only, works in reverse, and does not affect CH01',()=>{
 const normal=Sim.newMatch(74,1);normal.status='playing';
 const old=normal.vehicle.speed;
 Sim.tick(normal,1/60,{crouch:true});
 assert.equal(normal.vehicle.speed,old);
 assert.equal(Sim.shuttleStatus(normal).braking,false);
 const g=driving(89),v=g.vehicle;
 for(let i=0;i<35;i++)Sim.tick(g,1/60,{back:true});
 assert.ok(v.speed<0);
 const before=v.speed;
 Sim.tick(g,1/60,{back:true,crouch:true});
 assert.ok(v.speed>before&&v.speed<=0,'negative speed moves continuously toward zero');
 for(let i=0;i<35;i++)Sim.tick(g,1/60,{back:true,crouch:true});
 assert.equal(v.speed,0);
 assert.equal(Sim.operateYardShuttle(g).event,'exit');
 assert.equal(Sim.shuttleStatus(g).braking,false);
 const story=require('../src/story-slice.js').createState();
 assert.equal(story.world.vehicle?.driver,false);
});
test('vehicle save restores the exact physical state and forgets held brake input',()=>{
 const g=driving(82);
 for(let i=0;i<35;i++)Sim.tick(g,1/60,{forward:true});
 Sim.tick(g,1/60,{crouch:true});
 const saved=Sim.snapshotMatch(g),restored=Sim.restoreMatch(saved);
 assert.deepEqual(restored.vehicle,g.vehicle);
 assert.equal(Sim.snapshotMatch(restored),saved);
 assert.equal(Sim.shuttleStatus(restored).braking,false,'cannot persist an unacknowledged held key');
 Sim.tick(restored,1/60,{});
 assert.equal(Sim.shuttleStatus(restored).braking,false);
 assert.equal(JSON.parse(saved).vehicle.speed,g.vehicle.speed);
 assert.equal(Object.hasOwn(JSON.parse(saved),'vehicleBrake'),false);
});
