'use strict';
// UE5 native actor replication contracts: these are SOURCE-LEVEL gates.
// Actual UBT compilation, Win64 packaging and multiplayer PIE remain separate.
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.join(__dirname,'..','Unreal','Veilpoint','Source','Veilpoint');
const read=(name)=>fs.readFileSync(path.join(base,name),'utf8');
const bootstrap=read('VPWorldBootstrap.cpp');
const gameMode=read('VPGameMode.cpp');
const pickup=read('VPPickup.cpp');

test('UE5 world bootstrap actor is network-relevant and created by server once',()=>{
 assert.match(bootstrap,/AVPWorldBootstrap::AVPWorldBootstrap\(\)[\s\S]*?bReplicates=true;/);
 assert.match(bootstrap,/bAlwaysRelevant=true;/);
 assert.match(bootstrap,/SetReplicateMovement\(false\);/);
 assert.match(gameMode,/if\(HasAuthority\(\)\)[\s\S]*?SpawnActor<AVPWorldBootstrap>/);
 assert.doesNotMatch(bootstrap,/bReplicates=false/);
});

test('UE5 ground, buildings and vegetation are generated by both server and client',()=>{
 const body=bootstrap.slice(bootstrap.indexOf('void AVPWorldBootstrap::BeginPlay()'));
 const gate=body.indexOf('if(HasAuthority())');
 assert.ok(gate>0,'pickup spawn must remain explicitly server-authoritative');
 for(const pattern of [/AddBlock\(Ground,/,
                       /AddBlock\(Buildings,/,
                       /AddBlock\(Vegetation,/
 ]) {
   const match=body.match(pattern);
   assert.ok(match,'static world instance missing');
   assert.ok(match.index<gate,'static geometry must exist on replicated client');
 }
 assert.match(bootstrap,/Ground->SetCollisionEnabled\(ECollisionEnabled::QueryAndPhysics\)/);
 assert.match(bootstrap,/Buildings->SetCollisionEnabled\(ECollisionEnabled::QueryAndPhysics\)/);
});

test('UE5 decoration is deterministic and native resources are authority only',()=>{
 const body=bootstrap.slice(bootstrap.indexOf('void AVPWorldBootstrap::BeginPlay()'));
 assert.match(body,/FRandomStream Random\(19771\)/);
 assert.match(body,/for\(int32 j=0;j<250;\+\+j\)/);
 assert.match(body,/if\(HasAuthority\(\)\)[\s\S]*?SpawnActor<AVPPickup>/);
 assert.match(pickup,/bReplicates=true;/);
 assert.match(pickup,/if \(!HasAuthority\(\) \|\| bConsumed/);
 assert.doesNotMatch(body.slice(0,body.indexOf('if(HasAuthority())')),/SpawnActor<AVPPickup>/);
});
