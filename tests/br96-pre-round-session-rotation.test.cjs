'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {BrSquadLobby}=require('../src/br-squad-lobby.cjs');
const {createBrSquadServer}=require('../server/br-squad-server.cjs');
const token=i=>i.toString(16).padStart(64,'0');
test('in-progress 16x6 staging preserves one real seat, readiness, invite, ballot and chat cooldown after token rotation',()=>{
 const lobby=new BrSquadLobby();
 const first=token(1),second=token(2),renewed=token(90);
 assert.equal(lobby.join(first,'원래 참가자').ok,true);
 assert.equal(lobby.join(second,'같은 팀').ok,true);
 assert.equal(lobby.voteEntry(first,'promenade').ok,true);
 assert.equal(lobby.chat(first,'잠시 후 시작',10000).ok,true);
 const invite=lobby.invite(first);
 assert.equal(invite.ok,true);
 assert.equal(lobby.ready(first,true).ok,true);
 const before=lobby.snapshot(first);
 assert.equal(lobby.rebindSession(first,renewed).ok,true);
 const after=lobby.snapshot(renewed);
 assert.deepEqual(after.self,before.self);
 assert.equal(after.entry.selfChoice,'promenade');
 assert.deepEqual(after.lobbyChat,before.lobbyChat);
 assert.equal(after.readyCount,1);
 assert.equal(after.participants,2);
 assert.equal(lobby.players.size,2);
 assert.equal(lobby.join(token(3),'초대받은 사람',invite.code).team,0);
 assert.equal(lobby.invite(renewed).code,invite.code,'existing invitation remains valid after authenticated rotation');
 assert.equal(lobby.chat(renewed,'시간 조절',12000).reason,'chat_cooldown');
 assert.equal(lobby.chat(renewed,'3초 후 다시',13500).ok,true);
 assert.throws(()=>lobby.snapshot(first),/unknown_session/);
 assert.throws(()=>lobby.ready(first,false),/unknown_session/);
 assert.equal(lobby.snapshot(second).squad.filter(Boolean).length,3);
 assert.equal(lobby.snapshot(second).phase,'assembling');
 assert.equal(JSON.stringify(lobby.snapshot(second)).includes(renewed),false,'roster must not disclose rotated secret');
});
test('loopback staging rotation is authenticated, rejects payload forgery and preserves real readiness',async()=>{
 const host=createBrSquadServer({port:0,autoTick:false});
 const addr=await host.listen(),base='http://127.0.0.1:'+addr.port;
 const post=async(route,body,secret)=>{
  const headers={'content-type':'application/json'};
  if(secret)headers['x-player-token']=secret;
  const response=await fetch(base+route,{method:'POST',headers,body:JSON.stringify(body)});
  return {status:response.status,body:await response.json()};
 };
 const get=async(route,secret)=>{
  const response=await fetch(base+route,{headers:{'x-player-token':secret}});
  return {status:response.status,body:await response.json()};
 };
 try{
  const joined=await post('/join',{name:'준비하는 참가자'});
  assert.equal(joined.status,201);
  const first=joined.body.token;
  assert.equal((await post('/entry-vote',{choice:'lane'},first)).status,200);
  const invite=await post('/squad-invite',{},first);
  assert.equal(invite.status,200);
  assert.equal((await post('/ready',{ready:true},first)).status,200);
  const before=await get('/state',first);
  assert.equal((await post('/resume-session',{team:5},first)).status,400);
  assert.equal((await post('/resume-session',{},'f'.repeat(64))).status,401);
  const rotated=await post('/resume-session',{},first);
  assert.equal(rotated.status,200);
  const next=rotated.body.token;
  assert.match(next,/^[a-f0-9]{64}$/);
  assert.notEqual(next,first);
  assert.equal(rotated.body.state.self.id,before.body.self.id);
  assert.equal(rotated.body.state.self.ready,true);
  assert.equal(rotated.body.state.entry.selfChoice,'lane');
  assert.equal(rotated.body.state.readyCount,1);
  assert.equal(rotated.body.state.participants,1);
  assert.equal((await get('/state',first)).status,401);
  assert.equal((await post('/ready',{ready:false},first)).status,401);
  const second=await post('/join',{name:'초대 팀원',inviteCode:invite.body.code});
  assert.equal(second.status,201);
  assert.equal(second.body.team,0);
  assert.equal(second.body.slot,1);
  assert.equal((await get('/world',next)).status,409,'pre-round handoff cannot instantiate a running world');
  assert.equal((await post('/resume-session',{},first)).status,401,'old token cannot be replayed');
  const latest=await get('/state',next);
  assert.equal(latest.body.readyCount,1);
  assert.equal(latest.body.participants,2);
  assert.equal(JSON.stringify(latest.body).includes(next),false);
  assert.equal(host.world,null);
 }finally{await host.close();}
});
